// Supabase Edge Function: send-push
// Immediate admin broadcast. Phase 2b: this is now a PRODUCER — it fans out one
// `notifications` row per user and lets `dispatch` deliver the push. It no longer
// talks to web-push directly, so `dispatch` is the single delivery path and every
// broadcast also lands in the in-app inbox with per-user read state.
//
// Auth: requests must carry either:
//   * x-push-key: <PUSH_ADMIN_SECRET> (cron/legacy admin callers), or
//   * a signed-in admin's Clerk bearer token. The latter is checked against
//     communications.send capability, so read-only monitors cannot send live pushes.
// Secrets required (supabase secrets set ...):
//   PUSH_ADMIN_SECRET
// SB_URL / SB_SERVICE_ROLE_KEY fall back to the platform-injected SUPABASE_* vars.
//
// Body: { title, body, url?, icon?, image?, tag?, mode?, target_user_id? }
//   mode: "digest" is a no-op; class-reminders owns personal morning summaries.
//   target_user_id: when set, fan out to just that one user (admin test push).
//   target_user_ids: when set, fan out to just this list of users (re-engagement).
//
// Behaviour note: the broadcast now gains up to ~1 min latency (it is delivered on
// the next `dispatch` cron tick) and each broadcast creates one 30-day inbox row
// per user. The admin health-check still relies on the "title and body required"
// 400 and a fast 2xx, so both are preserved.

import { createClient } from "npm:@supabase/supabase-js@2";
import { pushImage } from "../_shared/pushPresentation.ts";

const CORS = {
  "Access-Control-Allow-Origin": "*",
  "Access-Control-Allow-Headers": "authorization, x-client-info, apikey, content-type, x-push-key",
  "Access-Control-Allow-Methods": "POST, OPTIONS",
};

function json(status: number, payload: unknown) {
  return new Response(JSON.stringify(payload), {
    status,
    headers: { ...CORS, "Content-Type": "application/json" },
  });
}

Deno.serve(async (req) => {
  if (req.method === "OPTIONS") return new Response("ok", { headers: CORS });
  if (req.method !== "POST") return json(405, { error: "POST only" });

  const adminSecret = Deno.env.get("PUSH_ADMIN_SECRET");
  const secretAuthorized = Boolean(adminSecret && req.headers.get("x-push-key") === adminSecret);
  let sessionAuthorized = false;

  if (!secretAuthorized) {
    const authorization = req.headers.get("authorization") || "";
    const bearerToken = authorization.replace(/^Bearer\s+/i, "").trim();
    const anonKey = Deno.env.get("SUPABASE_ANON_KEY") || "";
    const supabaseUrl = Deno.env.get("SB_URL") ?? Deno.env.get("SUPABASE_URL") ?? "";

    if (bearerToken && anonKey && supabaseUrl) {
      const caller = createClient(supabaseUrl, anonKey, {
        global: { headers: { Authorization: `Bearer ${bearerToken}` } },
        auth: { persistSession: false, autoRefreshToken: false },
      });
      const { data, error } = await caller.rpc('admin_has_capability', { p_capability: 'communications.send' });
      sessionAuthorized = !error && data === true;
    }
  }

  if (!secretAuthorized && !sessionAuthorized) {
    return json(401, { error: "Unauthorized" });
  }

  let body: Record<string, string> = {};
  try {
    body = await req.json();
  } catch {
    return json(400, { error: "Invalid JSON body" });
  }

  let { title, body: message, url, icon, image, mode, target_user_id, target_user_ids } = body as {
    title?: string; body?: string; url?: string; icon?: string; image?: string; mode?: string;
    target_user_id?: string; target_user_ids?: string[];
  };
  if (mode === "digest") {
    // Legacy generic-digest cron must not duplicate the personal morning summary
    // or bypass its opt-in / configured time. class-reminders is the sole producer.
    return json(200, { queued: 0, skipped: "Personal daily summaries are generated by class-reminders" });
  }
  if (!title || !message) return json(400, { error: "title and body are required" });
  if (image && !pushImage(image)) return json(400, { error: "image must be an HTTPS URL or a local absolute path" });

  const supabase = createClient(
    Deno.env.get("SB_URL") ?? Deno.env.get("SUPABASE_URL")!,
    Deno.env.get("SB_SERVICE_ROLE_KEY") ?? Deno.env.get("SUPABASE_SERVICE_ROLE_KEY")!,
  );

  // Fan out to every known user — not just current push subscribers — so a user
  // without a live push subscription still gets the in-app inbox entry; `dispatch`
  // simply skips the push for them. When target_user_id is set (admin "Send test
  // to me"), deliver to that single user only for a real end-to-end preview.
  const ids = target_user_id ? [target_user_id] : (Array.isArray(target_user_ids) ? target_user_ids : null);
  const usersQuery = supabase.from("profiles").select("user_id");
  const { data: users, error } = ids
    ? await usersQuery.in("user_id", ids)
    : await usersQuery;
  if (error) return json(500, { error: error.message });
  if (!users || users.length === 0) return json(200, { queued: 0 });

  // One dedup_key for the whole broadcast, shared across all user rows: it makes
  // (user_id, dedup_key) unique per user and lets a retried insert be idempotent.
  const dedupKey = "broadcast:" + crypto.randomUUID();
  const rows = users.map((u) => ({
    user_id: u.user_id,
    type: "admin_broadcast",
    title,
    body: message,
    url: url || "/",
    icon: icon || null,
    data: { urgency: "normal", ttl: 12 * 3600, image: pushImage(image) },
    dedup_key: dedupKey,
  }));

  const { data: inserted, error: insErr } = await supabase
    .from("notifications")
    .upsert(rows, { onConflict: "user_id,dedup_key", ignoreDuplicates: true })
    .select("id");
  if (insErr) return json(500, { error: insErr.message });

  return json(200, { queued: inserted?.length ?? 0 });
});
